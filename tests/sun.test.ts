const store: Record<string, string> = {};
(globalThis as any).window = globalThis;
(globalThis as any).localStorage = { getItem: (k: string) => store[k] ?? null, setItem: (k: string, v: string) => { store[k] = v; }, removeItem: (k: string) => { delete store[k]; } };
import { addSun, sunOf, piecesFor, capped, stopOf, goalMinutes, JAR_SIZE, DAILY_CAP } from "../src/lib/walk/sunlight";
import { readGame } from "../src/lib/game/gameStore";
import { stickers } from "../src/lib/game/collection";
let fail = 0; const ok = (c: boolean, m: string) => { if (!c) { fail++; console.log("FAIL", m); } };
ok(piecesFor("motion", 1999, 0) === 19 && piecesFor("mind", 5000, 125_000) === 2, "pieces");
ok(goalMinutes(2000) === 20, "goal minutes");
let r = addSun(15, "2026-11-18");
ok(r.added === 15 && r.stops.length === 0 && r.after.inJar === 15, "first walk " + JSON.stringify(r));
r = addSun(30, "2026-11-18");
ok(r.added === 30 && r.stops.map((s) => s.n).join() === "1,2" && r.after.inJar === 5 && r.after.jars === 2, "two jars " + JSON.stringify(r.stops));
ok(stopOf(1).name === "첫 햇살 언덕" && stopOf(9).name.startsWith("햇살 별 1"), "stops");
r = addSun(500, "2026-11-18");
ok(r.added === DAILY_CAP - 45, "daily cap " + r.added);
ok(addSun(10, "2026-11-18").added === 0, "cap holds today");
ok(addSun(10, "2026-11-19").added === 10, "cap resets next day");
const s = sunOf(readGame(), "2026-11-19");
ok(s.total === DAILY_CAP + 10 && s.inJar === (DAILY_CAP + 10) % JAR_SIZE, "state " + JSON.stringify(s));
ok(capped(5, { ...s, today: { date: "x", n: DAILY_CAP - 2 } }) === 2, "capped");
const sun = stickers(readGame()).groups.find((g) => g.id === "sun")!;
ok(sun.items.filter((i) => i.earned).length === Math.floor(s.total / JAR_SIZE), "journey stickers " + sun.items.filter((i) => i.earned).length);
console.log(fail ? `${fail} FAILED` : "sun-unit: all passed");
