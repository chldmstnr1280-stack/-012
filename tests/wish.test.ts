import { catOf, ladder, TINIEST } from "../src/data/wishes";
let fail = 0; const ok = (c: boolean, m: string) => { if (!c) { fail++; console.log("FAIL", m); } };
ok(catOf("작가가 되고 싶어") === "create", "create"); ok(catOf("내 카페를 열고 싶어") === "business", "biz");
ok(catOf("유학 가고 싶어") === "study", "study"); ok(catOf("푹 자고 싶어") === "rest", "rest");
