ok(todaysAsk([w, w2], "2026-11-03") === null, "one per day");
ok(answer(w, "did", "2026-11-03", 4).wish.light === 1, "no double light");
ok(todaysAsk([w, w2], "2026-11-04")?.id === w2.id, "rotate");
